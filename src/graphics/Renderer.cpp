static unsigned int compileShader(unsigned int type, const char *source) {
  unsigned int id = glCreateShader(type);
  glShaderSource(id, 1, &source, nullptr);
  glCompileShader(id);

  int success;
  glGetShaderiv(id, GL_COMPILE_STATUS, &success);
  if (!success) {
    char infoLog[512];
    glGetShaderInfoLog(id, 512, nullptr, infoLog);
    std::cerr << "❌ Shader compilation failed:\n" << infoLog << std::endl;
    glDeleteShader(id);
    return 0;
  }
  return id;
}

static unsigned int createShaderProgram() {
  const char *vertexShaderSource = R"(
        #version 330 core
        layout (location = 0) in vec2 aPos;
        layout (location = 1) in vec2 aTexCoord;
        out vec2 TexCoord;
        uniform mat4 projection;
        uniform mat4 model;
        void main() {
            gl_Position = projection * model * vec4(aPos, 0.0, 1.0);
            TexCoord = aTexCoord;
        }
    )";

  const char *fragmentShaderSource = R"(
        #version 330 core
        in vec2 TexCoord;
        out vec4 FragColor;
        uniform vec4 color;
        uniform bool useTexture;
        uniform sampler2D texture0;
        void main() {
            if (useTexture) {
                FragColor = texture(texture0, TexCoord);
            } else {
                FragColor = color;
            }
        }
    )";

  unsigned int vertexShader =
      compileShader(GL_VERTEX_SHADER, vertexShaderSource);
  unsigned int fragmentShader =
      compileShader(GL_FRAGMENT_SHADER, fragmentShaderSource);

  unsigned int shaderProgram = glCreateProgram();
  glAttachShader(shaderProgram, vertexShader);
  glAttachShader(shaderProgram, fragmentShader);
  glLinkProgram(shaderProgram);

  int success;
  glGetProgramiv(shaderProgram, GL_LINK_STATUS, &success);
  if (!success) {
    char infoLog[512];
    glGetProgramInfoLog(shaderProgram, 512, nullptr, infoLog);
    std::cerr << "❌ Shader program linking failed:\n" << infoLog << std::endl;
  }

  glDeleteShader(vertexShader);
  glDeleteShader(fragmentShader);
  return shaderProgram;
}

Renderer::Renderer(int width, int height) : m_width(width), m_height(height) {
  m_shaderProgram = createShaderProgram();
  if (!m_shaderProgram) {
    std::cerr << "❌ Failed to create shader program!\n";
    exit(1);
  }
  glEnable(GL_BLEND);
  glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
  float vertices[] = {
      -0.5f, -0.5f, 0.0f, 0.0f, 
      0.5f,  -0.5f, 1.0f, 0.0f, 
      0.5f,  0.5f,  1.0f, 1.0f, 
      -0.5f, 0.5f,  0.0f, 1.0f  
  };
  unsigned int indices[] = {0, 1, 2, 2, 3, 0};

  glGenVertexArrays(1, &m_vao);
  glGenBuffers(1, &m_vbo);
  glGenBuffers(1, &m_ebo);

  glBindVertexArray(m_vao);
  glBindBuffer(GL_ARRAY_BUFFER, m_vbo);
  glBufferData(GL_ARRAY_BUFFER, sizeof(vertices), vertices, GL_STATIC_DRAW);
  glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, m_ebo);
  glBufferData(GL_ELEMENT_ARRAY_BUFFER, sizeof(indices), indices,
               GL_STATIC_DRAW);

  glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void *)0);
  glEnableVertexAttribArray(0);
  glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float),
                        (void *)(2 * sizeof(float)));
  glEnableVertexAttribArray(1);

  glBindVertexArray(0);

  glm::mat4 proj =
      glm::ortho(0.0f, (float)width, 0.0f, (float)height, -1.0f, 1.0f);
  glUseProgram(m_shaderProgram);
  glUniformMatrix4fv(glGetUniformLocation(m_shaderProgram, "projection"), 1,
                     GL_FALSE, glm::value_ptr(proj));

  std::cout << "✅ Renderer initialized (" << width << "x" << height << ")\n";
}

Renderer::~Renderer() {
  if (m_vao)
    glDeleteVertexArrays(1, &m_vao);
  if (m_vbo)
    glDeleteBuffers(1, &m_vbo);
  if (m_ebo)
    glDeleteBuffers(1, &m_ebo);
  if (m_shaderProgram)
    glDeleteProgram(m_shaderProgram);
}

void Renderer::beginFrame() {
  glClearColor(0.05f, 0.02f, 0.15f, 1.0f); 
  glClear(GL_COLOR_BUFFER_BIT);
}

void Renderer::endFrame() {}

void Renderer::drawQuad(const Vector2 &pos, const Vector2 &size, float r,
                        float g, float b, float rotation) {
  glUseProgram(m_shaderProgram);
  glUniform4f(glGetUniformLocation(m_shaderProgram, "color"), r, g, b, 1.0f);
  glUniform1i(glGetUniformLocation(m_shaderProgram, "useTexture"), 0);

  glm::mat4 model = glm::mat4(1.0f);
  model =
      glm::translate(model, glm::vec3(pos.x, pos.y, 0.0f)); 
  model = glm::rotate(model, rotation,
                      glm::vec3(0.0f, 0.0f, 1.0f)); 
  model = glm::scale(model, glm::vec3(size.x, size.y, 1.0f)); 

  glUniformMatrix4fv(glGetUniformLocation(m_shaderProgram, "model"), 1,
                     GL_FALSE, glm::value_ptr(model));

  glBindVertexArray(m_vao);
  glDrawElements(GL_TRIANGLES, 6, GL_UNSIGNED_INT, 0);
}

