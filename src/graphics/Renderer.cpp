float Renderer::textWidth(const char *text, float scale) const {
  if (!text) return 0.0f;
  int len = static_cast<int>(std::strlen(text));
  if (len == 0) return 0.0f;
  return static_cast<float>(len) * 6.0f * scale - scale; 
}

void Renderer::drawText(const Vector2 &pos, const char *text, float scale,
                        float r, float g, float b, float a) {
  if (!text) return;
  float px = pos.x;
  float charAdvance = 6.0f * scale; 

  for (const char *p = text; *p; ++p) {
    int ch = static_cast<unsigned char>(*p);
    if (ch < 32 || ch > 126) ch = '?';

    const unsigned char *glyph = FONT_5X7[ch - 32];
    for (int row = 0; row < 7; ++row) {
      unsigned char bits = glyph[row];
      if (bits == 0) continue; 
      for (int col = 0; col < 5; ++col) {
        if (bits & (1 << (4 - col))) {
          float qx = px + static_cast<float>(col) * scale + scale * 0.5f;
          float qy = pos.y + static_cast<float>(6 - row) * scale + scale * 0.5f;
          drawQuadAlpha({qx, qy}, {scale, scale}, r, g, b, a, 0.0f);
        }
      }
    }
    px += charAdvance;
  }
}

void Renderer::drawTextCentered(const Vector2 &pos, const char *text,
                                float scale, float r, float g, float b,
                                float a) {
  float w = textWidth(text, scale);
  float h = 7.0f * scale;
  drawText({pos.x - w * 0.5f, pos.y - h * 0.5f}, text, scale, r, g, b, a);
}

